# 定义一个“减轻数字倾斜”的处理方法
def deskew(image):
    moments = cv2.moments(image)

    # 如果无法可靠计算倾斜程度，就保留原图
    if abs(moments["mu02"]) < 0.01:
        return image.copy()

    # 根据笔画分布估计倾斜程度
    skew = moments["mu11"] / moments["mu02"]

    # 设置校正方式
    matrix = np.float32([
        [1, skew, -10 * skew],
        [0, 1, 0]
    ])

    # 执行校正，图片仍保持20×20像素
    corrected = cv2.warpAffine(
        image,
        matrix,
        (20, 20),
        flags=cv2.WARP_INVERSE_MAP | cv2.INTER_LINEAR
    )

    return corrected


